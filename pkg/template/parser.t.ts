import type { ParseMapContext } from "./node/map.t.ts"

/**
 * Контекст парсера для разрешения путей к данным.
 *
 * Используется при парсинге для отслеживания текущего положения в иерархии:
 * - Вне map — `currentPath` содержит абсолютный путь (например, `"/fields/user"`)
 * - В map — `mapParams` содержит параметры функции, `level` указывает на вложенность
 * - Во вложенном map — `mapContextStack` хранит контексты всех родительских map
 */
export type ParseContext = {
  /** Текущий путь к данным (например, `"/fields/user"`, `"[item]/nested"`) */
  currentPath?: string
  /** Стек путей для навигации по вложенным структурам */
  pathStack: string[]
  /**
   * Параметры текущей map функции.
   *
   * - Для `.map((item) => ...)` → `["item"]`
   * - Для `.map(({ title, id }) => ...)` → `["title", "id"]`
   */
  mapParams?: string[]
  /** Уровень вложенности (0 для корневого, 1 для вложенного map) */
  level: number
  /** Стек контекстов всех map для разрешения переменных из родительских областей */
  mapContextStack?: ParseMapContext[]
}

/**
 * Результат парсинга пути к данным.
 */
export type ParseResult = {
  /** Извлечённый путь к данным (строка или массив для сложных условий) */
  path: string | string[]
  /** Контекст для вложенных операций (если был создан новый) */
  context?: ParseContext
  /** Дополнительные метаданные (например, `{ expression: "${[0]} > 0" }`) */
  metadata?: Record<string, any>
}

/**
 * Статическое строковое значение.
 * @group Варианты значений
 */
export type ValueStatic = string

/**
 * Переменный атрибут с путём к данным.
 *
 * Используется для простых динамических атрибутов без выражений.
 *
 * @group Варианты значений
 * @example Простой атрибут
 * ```html
 * <div class="${fields.theme}">Тема пользователя</div>
 * ```
 *
 * Результат:
 * ```typescript
 * { data: "/fields/theme" }
 * ```
 */
export type ValueVariable = {
  /**
   * Путь к данным в формате парсера.
   *
   * Форматы путей:
   * - `/fields/...` — доступ к полям контекста
   * - `/mass/...` — доступ к mass объекту
   * - `[item]/...` — доступ к элементу итерации в map
   * - `[index]` — индекс элемента в map
   * - `../[item]/...` — доступ к родительскому контексту map
   */
  data: string
}

/**
 * Динамический атрибут с выражением и путями к данным.
 *
 * Используется для сложных вычислений в атрибутах:
 * - Тернарные операторы (`condition ? 'a' : 'b'`)
 * - Логические выражения (`a && b || c`)
 * - Математические операции (`count + 1`)
 * - Вызовы методов (`name.toUpperCase()`)
 *
 * @group Варианты значений
 * @example Тернарный оператор
 * ```html
 * <div class="${mass.role === 'admin' ? 'admin-panel' : 'user-panel'}">
 *   Панель управления
 * </div>
 * ```
 *
 * Результат:
 * ```typescript
 * {
 *   data: ["/mass/role"],
 *   expr: "${_[0]} === 'admin' ? 'admin-panel' : 'user-panel'"
 * }
 * ```
 */
export type ValueDynamic = {
  /**
   * Путь(и) к данным, используемым в выражении.
   *
   * Массив используется для сложных выражений с несколькими переменными.
   */
  data: string | string[]
  /**
   * Унифицированное выражение с индексами.
   *
   * Индексы (`_[0]`, `_[1]`) ссылаются на элементы массива `data`.
   *
   * @example
   * ```typescript
   * expr: "${_[0]} === 'admin' ? 'admin' : 'user'"
   * ```
   */
  expr: string
}
