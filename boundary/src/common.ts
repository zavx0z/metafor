/**
 * Коды операций сравнения, используемые в байт-коде.
 * Эти значения должны бинарно совпадать с константами в WGSL-шейдере (`classify.wgsl`).
 * @enum {number}
 */
export const OP = {
  /** Равно (`==`) */
  EQ: 0,
  /** Не равно (`!=`) */
  NEQ: 1,
  /** Больше (`>`) */
  GT: 2,
  /** Меньше (`<`) */
  LT: 3,
  /** Больше или равно (`>=`) */
  GTE: 4,
  /** Меньше или равно (`<=`) */
  LTE: 5,
  /** Входит в список (`in`) */
  IN: 6,
  /** Не входит в список (`notIn`) */
  NOT_IN: 7,
  /** Содержит элемент (`include`) - для массивов */
  INCLUDE: 8,
  /** Не содержит элемент (`notInclude`) */
  NOT_INCLUDE: 9,
  /** Длина равна/сравнение (`length`) */
  LENGTH: 10,
  /** Пустой (`isEmpty`) */
  IS_EMPTY: 11,
} as const

/**
 * Типы данных для компонент браны.
 * Определяет, из какого типизированного массива (`floats` или `uints`) шейдер будет считывать значение.
 * @enum {number}
 */
export const TYPE = {
  /** 32-битное число с плавающей точкой. */
  FLOAT: 0,
  /** 32-битное беззнаковое целое число. */
  UINT: 1,
  /** Булево значение (хранится как UINT). */
  BOOL: 2,
  /** Строка (хранится как ссылка на атлас символов). */
  STRING: 3,
  /** Массив (хранится как длина + указатели на элементы). */
  ARRAY: 4,
} as const

/**
 * Числовой идентификатор состояния, соответствующий его индексу в таблице состояний.
 * @typedef {number} StateID
 */
export type StateID = number

/**
 * Представляет результат компиляции правил — артефакты, готовые для загрузки на GPU.
 * Содержит байт-код и метаданные, необходимые для его интерпретации.
 */
export interface CompiledRules {
  /**
   * Скомпилированные правила в виде плоского массива 32-битных беззнаковых целых чисел.
   * Этот массив представляет собой программу для кастомной VM, исполняемой на GPU.
   * Его структура включает в себя несколько секций:
   * 1. **Таблица состояний (State Table):** Карта `StateID -> указатель на блок состояния`.
   * 2. **Блоки состояний (State Blocks):** Описывают переходы для каждого состояния.
   * 3. **Блоки переходов (Transition Blocks):** Содержат указатели на условия.
   * 4. **Блоки условий (Condition Blocks):** Набор инструкций для проверки полей браны.
   */
  bytecode: Uint32Array

  /**
   * Смещение (в `u32` словах) от начала `bytecode` до таблицы состояний.
   */
  stateTableOffset: number

  /**
   * Карта, связывающая строковые имена состояний (например, `"IDLE"`) с их числовыми идентификаторами (`StateID`).
   * @example ` { "IDLE": 0, "WALK": 1, "DEAD": 2 }`
   */
  stateMap: Record<string, number>
}
